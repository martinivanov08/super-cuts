/* ── Custom Datepicker ─────────────────────────────── */
(function () {
    const BG_MONTHS = ['Януари','Февруари','Март','Април','Май','Юни',
                       'Юли','Август','Септември','Октомври','Ноември','Декември'];

    let selectedDate = null;
    const today = new Date(); today.setHours(0,0,0,0);
    let viewYear  = today.getFullYear();
    let viewMonth = today.getMonth();

    const wrap      = document.getElementById('datepickerWrap');
    const display   = document.getElementById('dpDisplay');
    const dpText    = document.getElementById('dpText');
    const dropdown  = document.getElementById('dpDropdown');
    const hidden    = document.getElementById('date');
    const prevBtn   = document.getElementById('dpPrev');
    const nextBtn   = document.getElementById('dpNext');
    const monthYear = document.getElementById('dpMonthYear');
    const grid      = document.getElementById('dpGrid');

    function pad(n) { return String(n).padStart(2, '0'); }

    function renderCalendar() {
        monthYear.textContent = BG_MONTHS[viewMonth] + ' ' + viewYear;
        grid.innerHTML = '';

        // First weekday of month (Mon=0)
        let startDow = new Date(viewYear, viewMonth, 1).getDay();
        startDow = startDow === 0 ? 6 : startDow - 1;

        const daysInMonth    = new Date(viewYear, viewMonth + 1, 0).getDate();
        const daysInPrevMonth = new Date(viewYear, viewMonth, 0).getDate();

        // Filler from previous month
        for (let i = startDow - 1; i >= 0; i--) {
            const btn = makeDay(daysInPrevMonth - i, true, true);
            grid.appendChild(btn);
        }

        // Current month
        for (let d = 1; d <= daysInMonth; d++) {
            const date = new Date(viewYear, viewMonth, d);
            const isPast = date < today;
            const isToday = date.toDateString() === today.toDateString();
            const isSelected = selectedDate && date.toDateString() === selectedDate.toDateString();

            const btn = makeDay(d, false, isPast);
            if (isToday)    btn.classList.add('today');
            if (isSelected) btn.classList.add('selected');

            if (!isPast) {
                btn.addEventListener('click', function () {
                    selectedDate = date;
                    hidden.value = viewYear + '-' + pad(viewMonth + 1) + '-' + pad(d);
                    dpText.textContent = pad(d) + '.' + pad(viewMonth + 1) + '.' + viewYear;
                    dpText.className = 'dp-selected-text';
                    close();
                    renderCalendar();
                });
            }
            grid.appendChild(btn);
        }

        // Filler to next month
        const filled = grid.children.length;
        const tail   = filled % 7 === 0 ? 0 : 7 - (filled % 7);
        for (let i = 1; i <= tail; i++) {
            grid.appendChild(makeDay(i, true, true));
        }
    }

    function makeDay(num, otherMonth, disabled) {
        const btn = document.createElement('button');
        btn.type = 'button';
        btn.textContent = num;
        btn.className = 'dp-day' + (otherMonth ? ' other-month' : '') + (disabled ? ' disabled' : '');
        if (disabled) btn.disabled = true;
        return btn;
    }

    function open()  { dropdown.style.display = 'block'; display.classList.add('open'); renderCalendar(); }
    function close() { dropdown.style.display = 'none';  display.classList.remove('open'); }

    display.addEventListener('click', function () {
        dropdown.style.display === 'none' ? open() : close();
    });
    display.addEventListener('keydown', function (e) {
        if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); display.click(); }
    });

    prevBtn.addEventListener('click', function () {
        if (--viewMonth < 0) { viewMonth = 11; viewYear--; }
        renderCalendar();
    });
    nextBtn.addEventListener('click', function () {
        if (++viewMonth > 11) { viewMonth = 0; viewYear++; }
        renderCalendar();
    });

    document.addEventListener('click', function (e) {
        if (!wrap.contains(e.target)) close();
    });
})();

/* ── Reservation form ──────────────────────────────── */
document.getElementById('reservationForm').addEventListener('submit', async function (e) {
    e.preventDefault();
    const btn = this.querySelector('.form-submit');
    const msg = document.getElementById('formMsg');

    if (!document.getElementById('date').value) {
        msg.className = 'form-msg error';
        msg.textContent = '✗ Моля, изберете дата.';
        msg.style.display = 'block';
        return;
    }

    btn.disabled = true;
    btn.textContent = 'Резервиране...';
    msg.style.display = 'none';

    try {
        const res  = await fetch('reserve.php', { method: 'POST', body: new FormData(this) });
        const data = await res.json();

        if (data.success) {
            msg.className = 'form-msg success';
            msg.textContent = '✓ Резервацията е потвърдена! Очакваме ви с нетърпение.';
            this.reset();
            // reset datepicker display
            const dpText = document.getElementById('dpText');
            dpText.textContent = 'дд.мм.гггг';
            dpText.className = 'dp-placeholder';
        } else {
            msg.className = 'form-msg error';
            msg.textContent = '✗ ' + (data.error || 'Нещо се обърка.');
        }
    } catch {
        msg.className = 'form-msg error';
        msg.textContent = '✗ Мрежова грешка. Моля, опитайте отново.';
    }

    msg.style.display = 'block';
    btn.disabled = false;
    btn.textContent = 'Потвърди Резервацията';
    msg.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
});
